// Pre-build ESM shims for CJS-only dependencies that Astro 7's sync/dev-server
// module-runner (`astro` Vite environment, rolldown-powered Vite 8) cannot
// load: it inlines their CommonJS dist as ESM and dies with "require is not
// defined" / "Class extends value undefined", and it cannot resolve bare
// specifiers under pnpm's strict layout when externalized.
//
// Usage: node scripts/build-cjs-shims.mjs <pkg> [pkg...]
//   pkg is a package name, optionally with an exact version ("picomatch",
//   "picomatch@4.0.7", "@foo/bar", "@foo/bar@1.2.3").
// Writes, per package:
//   scripts/shims/_bundles/<pkg>.mjs   rolldown bundle of the CJS entry
//   scripts/shims/<pkg>.mjs            wrapper re-exporting default + named keys
// and prints the alias line to paste into astro.config.mjs.
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { existsSync, readdirSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
// rolldown is a transitive dependency (astro -> vite -> rolldown); resolve it
// through that chain because pnpm's strict layout hides it from this script.
const astroRequire = createRequire(require.resolve('astro/package.json'))
const viteRequire = createRequire(astroRequire.resolve('vite/package.json'))
const { rolldown } = await import(pathToFileURL(viteRequire.resolve('rolldown')))
const outDir = path.join(path.dirname(fileURLToPath(import.meta.url)), 'shims')
const bundleDir = path.join(outDir, '_bundles')
await mkdir(bundleDir, { recursive: true })

// Split "name[@version]" (scoped names keep their inner slash).
function parseSpec(spec) {
  const at = spec.startsWith('@') ? spec.indexOf('@', 1) : spec.indexOf('@')
  return at === -1 ? [spec, undefined] : [spec.slice(0, at), spec.slice(at + 1)]
}

// Locate a package inside pnpm's virtual store (transitive packages are not
// hoisted to the project root, so require.resolve cannot see them).
function findInStore(name, version) {
  const store = path.join(root, 'node_modules', '.pnpm')
  const prefix = `${name.replace('/', '+')}@`
  const hits = existsSync(store)
    ? readdirSync(store).filter((d) => d.startsWith(prefix) && (version ? d === `${prefix}${version}` : d.includes('@'))).sort()
    : []
  if (hits.length === 0) throw new Error(`Cannot find ${prefix}* in ${store}`)
  return path.join(store, hits.at(-1), 'node_modules', name)
}

async function entryOf(pkg) {
  const direct = path.join(root, 'node_modules', pkg)
  const pkgDir = existsSync(direct) ? direct : findInStore(...parseSpec(pkg))
  const pj = JSON.parse(await readFile(path.join(pkgDir, 'package.json'), 'utf8'))
  return path.join(pkgDir, pj.main ?? 'index.js')
}

const IDENT = /^[$_A-Za-z][$_A-Za-z0-9]*$/

for (const pkg of process.argv.slice(2)) {
  const safeName = pkg.replace(/[^a-z0-9._@/-]/gi, '_')
  const bundleFile = path.join(bundleDir, `${safeName}.mjs`)
  const wrapperFile = path.join(outDir, `${safeName}.mjs`)

  const bundle = await rolldown({ input: await entryOf(pkg), platform: 'node' })
  const { output } = await bundle.generate({ format: 'esm' })
  await writeFile(bundleFile, output[0].code)
  await bundle.close()

  // Enumerate the CJS module's export keys at build time so the wrapper can
  // re-export them as real named ESM exports (rolldown's CJS interop only
  // provides a default export).
  const mod = (await import(pathToFileURL(bundleFile))).default
  const keys = [...new Set([...Object.keys(mod ?? {}), ...(mod?.default ? Object.keys(mod.default) : [])])]
    .filter((k) => IDENT.test(k) && k !== 'default')
  const lines = [
    `// Generated by scripts/build-cjs-shims.mjs for "${pkg}". Do not edit.`,
    `import _d from './_bundles/${safeName}.mjs'`,
    'export default _d',
    ...keys.map((k) => `export const ${k} = _d[${JSON.stringify(k)}] ?? _d?.default?.[${JSON.stringify(k)}]`),
    '',
  ]
  await writeFile(wrapperFile, lines.join('\n'))
  console.log(`built ${path.relative(root, wrapperFile)} (named: ${keys.join(', ') || 'none'})`)
  const escaped = parseSpec(pkg)[0].replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
  console.log(`{ find: /^${escaped}$/, replacement: fileURLToPath(new URL('./scripts/shims/${path.basename(wrapperFile)}', import.meta.url)) },`)
}
