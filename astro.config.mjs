function normalizeBase(value) {
  const raw = (value ?? '').trim()
  if (!raw || raw === '/') return '/'
  return `/${raw.replace(/^\/+|\/+$/g, '')}/`
}

function normalizeSite(value) {
  const raw = (value ?? '').trim()
  if (!raw) return 'https://penglonghuang.github.io'
  if (/^https?:\/\//i.test(raw)) return raw.replace(/\/$/, '')
  return `https://${raw.replace(/^\/+/, '').replace(/\/$/, '')}`
}

// Astro's dev server does not resolve public/ directory indexes; static hosts do.
// Keep course URLs clean in production and teach only the dev server the same rule.
function courseDirectoryIndex() {
  return {
    name: 'course-directory-index',
    apply: 'serve',
    enforce: 'pre',
    configureServer(server) {
      server.middlewares.use((req, _res, next) => {
        if (!req.url) return next()
        const [pathname, query] = req.url.split('?')
        if (/\/learning\/[^/]+\/$/.test(pathname)) {
          req.url = `${pathname}index.html${query ? `?${query}` : ''}`
        }
        next()
      })
    },
  }
}

// Use the last built Pagefind index while viewing the site in Astro dev.
// The production index is still generated by the normal build command.
function developmentSearchIndex() {
  const directory = fileURLToPath(new URL('./dist/_pagefind/', import.meta.url))
  return {
    name: 'development-search-index',
    apply: 'serve',
    configureServer(server) {
      server.middlewares.use((req, res, next) => {
        const pathname = (req.url ?? '').split('?')[0]
        // Vite may already have removed the configured site base.
        const prefix = [`${BASE}_pagefind/`, '/_pagefind/'].find(value => pathname.startsWith(value))
        if (!prefix) return next()
        const filename = pathname.slice(prefix.length)
        if (!/^[a-zA-Z0-9_./-]+$/.test(filename)) return next()
        const file = resolve(directory, filename)
        if (!file.startsWith(resolve(directory) + sep)) return next()
        try { if (!statSync(file).isFile()) return next() } catch { return next() }
        const types = { '.js': 'text/javascript', '.json': 'application/json', '.wasm': 'application/wasm' }
        res.setHeader('Content-Type', types[extname(file)] ?? 'application/octet-stream')
        res.setHeader('Cache-Control', 'no-cache')
        const stream = createReadStream(file)
        stream.on('error', () => res.destroy())
        stream.pipe(res)
      })
    },
  }
}

